def build():
    i = TODAY.toordinal() % len(TIPS)
    title, insight, action, ref = TIPS[i]
    a = DECO[TODAY.toordinal() % len(DECO)]
    msg = (f"{a} 오늘의 브랜드 한 수\n\n"
           f"[{title}]\n{insight}\n\n"
           f"✦ 실행 — {action}\n"
           f"📚 ref: {ref}")
    return msg


def send(msg):
    tok = os.environ.get("TELEGRAM_BOT_TOKEN", "").strip()
    cid = os.environ.get("TELEGRAM_CHAT_ID", "").strip()
    if not tok or not cid:
        print("토큰/chat_id 미설정 → 출력만\n" + msg)
        return
    try:
        r = requests.post(f"https://api.telegram.org/bot{tok}/sendMessage",
                          json={"chat_id": cid, "text": msg, "disable_web_page_preview": True}, timeout=20)
        r.raise_for_status()
        print("marketing 발송 OK", len(msg), "자")
    except Exception as e:
        print("발송 실패", e)


if __name__ == "__main__":
    send(build())
